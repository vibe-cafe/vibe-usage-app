struct ProviderGlyph: View {
    let provider: ProviderRateLimit.Provider
    /// Side of the square the mark is drawn in (the design's 18 / 16 pt).
    var size: CGFloat = 18

    var body: some View {
        ProviderGlyphShape(provider: provider)
            .fill(style: FillStyle(eoFill: true))
            .frame(width: drawnSize, height: drawnSize)
    }

    /// The Lobe marks fill their 24-unit box to different extents. These
    /// ratios were measured against the finalized design's table (2× pixels)
    /// so each mark is drawn at the size the design shows it, e.g. Codex,
    /// Claude and Cursor 15 pt tall in an 18 pt slot.
    private var drawnSize: CGFloat {
        let ratio: CGFloat
        switch provider {
        case .codex, .claudeCode, .cursor: ratio = 0.833
        case .kimiCode: ratio = 0.994
        case .zCode: ratio = 0.861
        case .grok: ratio = 0.978
        case .opencodeGo: ratio = 0.933
        case .antigravity: ratio = 0.856
        }
        return size * ratio
    }
}

